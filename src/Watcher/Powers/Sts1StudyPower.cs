/// <summary>StS1 Study: at the end of the owner's turn, shuffle Amount Insights into their draw pile.</summary>
public sealed class Sts1StudyPower : PowerModel, IBorrowedIcon
{
	public override PowerType Type => PowerType.Buff;

	public override PowerStackType StackType => PowerStackType.Counter;

	public Type IconSource => typeof(PagestormPower);

	public override async Task BeforeSideTurnEnd(PlayerChoiceContext choiceContext, CombatSide side, IEnumerable<Creature> participants)
	{
		if (!participants.Contains(Owner) || Owner.Player == null)
		{
			return;
		}
		Flash();
		for (int i = 0; i < Amount; i++)
		{
			CardModel insight = CombatState.CreateCard<Sts1Insight>(Owner.Player);
			await CardPileCmd.AddGeneratedCardToCombat(insight, PileType.Draw, Owner.Player, CardPilePosition.Random);
		}
	}
}
