namespace SlaySpoon.Cards.Sts1.Watcher;

/// <summary>StS1 Master Reality: every card created for the owner during combat is Upgraded.</summary>
public sealed class Sts1MasterReality : Sts1WatcherCard
{
	public Sts1MasterReality()
		: base(1, CardType.Power, CardRarity.Rare, TargetType.Self)
	{
	}

	protected override async Task OnPlay(PlayerChoiceContext choiceContext, CardPlay cardPlay)
	{
		await PowerCmd.Apply<Sts1MasterRealityPower>(choiceContext, Owner.Creature, 1m, Owner.Creature, this);
	}

	protected override void OnUpgrade()
	{
		EnergyCost.UpgradeBy(-1);
	}
}
